def test_scoped_defaults_and_analytics_privileges(migrated, postgres_url):
    _, engine = migrated
    # New objects, not just existing foundation tables, inherit scoped grants.
    with engine.connect() as conn:
        with conn.begin():
            conn.execute(sa.text("CREATE TABLE auth.permission_probe (id integer)"))
            conn.execute(sa.text("CREATE VIEW analytics.probe AS SELECT 1 AS value"))
            assert conn.scalar(
                sa.text("SELECT has_table_privilege('app_rw', 'auth.permission_probe', 'INSERT')")
            )
            assert not conn.scalar(
                sa.text("SELECT has_table_privilege('app_analytics_ro', 'core.app_user', 'SELECT')")
            )
            assert conn.scalar(
                sa.text(
                    "SELECT has_table_privilege('app_analytics_ro', 'analytics.probe', 'SELECT')"
                )
            )
            assert not conn.scalar(
                sa.text("SELECT has_table_privilege('app_rw', 'analytics.probe', 'INSERT')")
            )
            assert not conn.scalar(
                sa.text(
                    "SELECT has_table_privilege('app_analytics_ro', 'analytics.probe', 'INSERT')"
                )
            )
        ro = sa.create_engine(role_url(postgres_url, "app_analytics_ro"))
        try:
            with ro.connect() as reader:
                assert reader.scalar(sa.text("SELECT value FROM analytics.probe")) == 1
                with pytest.raises(DBAPIError) as error:
                    reader.execute(sa.text("SELECT * FROM core.app_user"))
                assert error.value.orig.sqlstate == "42501"
        finally:
            ro.dispose()
        with conn.begin():
            conn.execute(sa.text("DROP VIEW analytics.probe"))
            conn.execute(sa.text("DROP TABLE auth.permission_probe"))


@pytest.mark.parametrize(
    "drift",
    [
        "ALTER TABLE core.app_user ADD COLUMN unexpected integer",
        "ALTER TABLE core.app_user ALTER COLUMN is_active SET DEFAULT false",
        "DROP TRIGGER app_user_audit ON core.app_user",
        "CREATE OR REPLACE FUNCTION audit.log_change() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$",
    ],
)
def test_check_detects_table_default_trigger_and_function_drift(migrated, drift):
    config, engine = migrated
    with engine.connect() as conn:
        transaction = conn.begin()
        config.attributes["connection"] = conn
        try:
            conn.execute(sa.text(drift))
            with pytest.raises(AutogenerateDiffsDetected):
                command.check(config)
        finally:
            config.attributes.pop("connection")
            transaction.rollback()


def test_idempotency_is_unique_per_user_and_rejects_unknown_user(migrated):
    _, engine = migrated
    with engine.begin() as conn:
        second_user = insert_user(conn)
        key = uuid4()
        statement = sa.text("""
            INSERT INTO core.idempotency_key (key, user_id, request_hash, response)
            VALUES (:key, :user_id, 'hash', '{"status": 201}'::jsonb)
        """)
        for user_id in (SYSTEM_ID, second_user):
            conn.execute(statement, {"key": key, "user_id": user_id})
        with pytest.raises(IntegrityError), conn.begin_nested():
            conn.execute(statement, {"key": key, "user_id": SYSTEM_ID})
        with pytest.raises(IntegrityError), conn.begin_nested():
            conn.execute(statement, {"key": key, "user_id": uuid4()})
        with pytest.raises(IntegrityError), conn.begin_nested():
            conn.execute(sa.text("DELETE FROM core.app_user WHERE id = :id"), {"id": second_user})


def test_replaceable_policy_create_replace_restore_drop(migrated):
    _, engine = migrated
    policy = ReplaceablePolicy(
        "core", 'policy"probe', 'read"policy', "FOR SELECT TO app_rw USING (id > 0)"
    )
    changed = ReplaceablePolicy(
        policy.schema, policy.table, policy.name, "FOR SELECT TO app_rw USING (id > 10)"
    )
    with engine.connect() as conn:
        transaction = conn.begin()
        try:
            conn.execute(sa.text('CREATE TABLE core."policy""probe" (id integer)'))
            with Operations.context(MigrationContext.configure(conn)):
                policy.create()
                changed.replace()
                assert (
                    conn.scalar(
                        sa.text("SELECT qual FROM pg_policies WHERE tablename = :table"),
                        {"table": policy.table},
                    )
                    == "(id > 10)"
                )
                policy.replace()  # A downgrade restores the previous definition.
                assert (
                    conn.scalar(
                        sa.text("SELECT qual FROM pg_policies WHERE tablename = :table"),
                        {"table": policy.table},
                    )
                    == "(id > 0)"
                )
                policy.drop()
                assert (
                    conn.scalar(
                        sa.text("SELECT count(*) FROM pg_policies WHERE tablename = :table"),
                        {"table": policy.table},
                    )
                    == 0
                )
        finally:
            transaction.rollback()
