"""Foundation migrations against PostgreSQL 18, using the actual infra role bootstrap.

Default: testcontainers postgres:18. On hosts without Docker, TEST_POSTGRES_URL
may point to a disposable PostgreSQL 18 database named test_*, already bootstrapped
with infra/postgres/init/01-roles.sh and the test passwords below. Never use a
shared or production database: these tests downgrade all application schemas.
"""

